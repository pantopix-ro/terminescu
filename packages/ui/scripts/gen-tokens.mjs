// Copies the design system's tokens and component styles into the app (D16). Source of truth:
// design/system/build_tokens.py, which writes design/system/project/tokens.{json,css}.
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../../../design/system/project/", import.meta.url);
const out = new URL("../src/generated/", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens.json", src), "utf8"));

const raw = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
const resolve = (v) => (v.startsWith("{") ? resolve(raw[v.slice(1, -1)]) : v);
const colors = Object.fromEntries(Object.keys(raw).map((k) => [k, resolve(raw[k])]));

const header = "// Generated by packages/ui/scripts/gen-tokens.mjs from design/system/project/tokens.json.\n";
writeFileSync(
  new URL("colors.ts", out),
  `${header}export const colors = ${JSON.stringify(colors, null, 2)} as const;\n\nexport type ColorToken = keyof typeof colors;\n`,
);
writeFileSync(new URL("tokens.css", out), readFileSync(new URL("tokens.css", src), "utf8"));

// Component styles from the design system, minus its remote font import: the app bundles
// its fonts (fonts.css) and its CSP allows no remote origin.
const bundle = readFileSync(new URL("components/bundle.css", src), "utf8")
  .split("\n")
  .filter((line) => !/^@import\s+url\(["']?https?:/.test(line))
  .join("\n");
writeFileSync(new URL("components.css", out), `/* Generated from design/system/project/components/bundle.css. */\n${bundle}`);
console.log(`tokens: ${Object.keys(colors).length} colors`);
